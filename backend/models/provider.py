"""Normalized Pydantic v2 DTOs shared across provider ABCs and adapters."""

from __future__ import annotations

from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from backend.models.enums import VisualSource


class WordTimestamp(BaseModel):
    """Word-level timing for karaoke .ass subtitles and audio alignment."""

    word: str
    start_ms: int = Field(..., ge=0)
    end_ms: int = Field(..., ge=0)
    confidence: float | None = None


class TranscriptSegment(BaseModel):
    """A recognized speech segment with optional speaker and word timings."""

    index: int = Field(..., ge=0)
    start_ms: int = Field(..., ge=0)
    end_ms: int = Field(..., ge=0)
    text: str
    speaker_label: str | None = None
    words: list[WordTimestamp] = Field(default_factory=list)


class TranscriptResult(BaseModel):
    """Normalized output from any BaseSTTProvider."""

    language: str | None = None
    duration_ms: int | None = Field(default=None, ge=0)
    full_text: str
    segments: list[TranscriptSegment] = Field(default_factory=list)


class VoiceOption(BaseModel):
    """Metadata describing an available TTS voice."""

    voice_id: str
    name: str
    language: str
    gender: str | None = None
    provider: str


class AudioSynthesisResult(BaseModel):
    """Normalized output from any BaseTTSProvider."""

    audio_path: Path
    duration_ms: int = Field(..., ge=0)
    voice_id: str
    rate_pct: int = 0
    provider: str


class TranslatedSegment(BaseModel):
    """Time-synced translated dialogue segment produced by BaseLLMProvider."""

    index: int = Field(..., ge=0)
    start_ms: int = Field(..., ge=0)
    end_ms: int = Field(..., ge=0)
    original_text: str
    translated_text: str
    target_syllables: int | None = None
    speaker_label: str | None = None


class StoryboardScene(BaseModel):
    """Single 3-5s scene generated for the AI Faceless Video pipeline."""

    scene_index: int = Field(..., ge=0)
    duration_seconds: float = Field(..., gt=0)
    narration_text: str
    search_keywords: str
    image_prompt: str
    emotion_tone: str


class StoryboardResult(BaseModel):
    """Structured storyboard generated by BaseLLMProvider."""

    title: str
    total_duration_seconds: float = Field(..., ge=0)
    scenes: list[StoryboardScene] = Field(default_factory=list)


class VisualAsset(BaseModel):
    """Normalized stock video/image or AI-generated visual returned by BaseVisualProvider."""

    url: str
    local_path: Path | None = None
    media_type: Literal["video", "image"] = "video"
    source: VisualSource
    width: int | None = None
    height: int | None = None
    duration_seconds: float | None = None
    attribution: str | None = None


class SeparationResult(BaseModel):
    """Output from vocal/BGM audio separation."""

    vocals_path: Path | None = None
    bgm_path: Path | None = None
    source_audio_path: Path
    mode: str


class StoredObject(BaseModel):
    """Metadata for an uploaded file in object storage."""

    bucket: str
    remote_key: str
    public_url: str | None = None
    signed_url: str | None = None
    size_bytes: int | None = None
